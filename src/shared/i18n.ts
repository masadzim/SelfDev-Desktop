const TABLES: Record<Language, Table> = { id, en };

/** Every key the table defines, so a missing translation is a test failure. */
export function keys(): string[] {
  return [...new Set([...Object.keys(id), ...Object.keys(en)])].sort();
}

/**
 * Looks a string up, falling back to Indonesian and then to the key itself.
 *
 * The fallback chain matters more than it looks: a half-finished translation
 * should read as Indonesian, not as `section.model` on screen.
 */
export function translate(language: Language, key: string, vars?: Record<string, string | number>): string {
  const raw = TABLES[language]?.[key] ?? id[key] ?? en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)}/g, (_, name: string) => {
    const value = vars[name];
    return value === undefined ? `{${name}}` : String(value);
  });
}

/** True when a key reads the same in both languages and so was not translated. */
export function isUntranslated(language: Language, key: string): boolean {
  return TABLES[language]?.[key] === undefined && id[key] !== undefined;
}